      <section className="lesson-section" id="observational-equivalence">
        <p className="section-kicker">37 · 观察等价</p>
        <h2>同一价格—成交路径可以由多种主体机制生成；异质框架扩大解释空间，也必须同步提高识别门槛。</h2>
        <p>
          价格上涨和主动买入可以来自正面私有信息、短仓回补、指数纳入、短 gamma 对冲或注意力冲击。“短 gamma”表示期权组合的 delta 会沿着不利方向随标的价格变化；若交易台以标的维持 delta 中性，典型再对冲就是上涨后买入、下跌后卖出，从而追随并放大原方向，但实际订单仍取决于其他期权敞口、客户流和对冲目标。价格下跌和机构卖出也可以来自基本面下修、赎回、风险限额或基准再平衡。只观察结果变量时，这些结构在数据中可能观察等价。更精细的故事不是更强证据。
        </p>
        <div className="equation-card">
          <span>结构不可识别的教学表达</span>
          <div>Y<sub>t</sub>=F(M<sub>1</sub>,ε<sub>1,t</sub>)=F(M<sub>2</sub>,ε<sub>2,t</sub>)</div>
          <p>Y 是观测到的价格、量和订单流，M<sub>1</sub>、M<sub>2</sub> 是竞争机制。若两套机制都能在自由选择冲击 ε 后复现 Y，Y 本身不能选择模型；必须寻找它们不能同时匹配的额外变量或干预。</p>
        </div>
        <p>
          破局证据包括冲击前持仓、账户身份、规则阈值、外生流量、期权敞口、信息到达顺序、未受影响对照组和机制特有的反转/持续预测。研究者应在看结果前写下竞争解释与排他预测，避免事后选择主体故事。
        </p>
      </section>

